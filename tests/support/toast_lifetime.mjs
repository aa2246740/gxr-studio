import { mock } from 'node:test';
import { pathToFileURL } from 'node:url';
import { installDom } from './mini_dom.mjs';

installDom();
mock.timers.enable({ apis: ['setTimeout', 'Date'] });
const { toast } = await import(pathToFileURL(`${process.argv[2]}/dom.js`).href);
const root = document.getElementById('toast-root');
const alive = (close) => root.contains(close.el) && !close.el.classList.contains('leaving');
const tick = (ms) => mock.timers.tick(ms);
const event = (close, name, relatedTarget = null) => {
  const e = new Event(name);
  Object.defineProperty(e, 'relatedTarget', { value: relatedTarget });
  close.el.dispatchEvent(e);
};
const out = {};
const info = toast('已保存');
tick(3199); out.infoBefore = alive(info);
tick(181); out.infoAfter = alive(info);
let ran = 0;
const action = toast('选择已清除', 'info', { timeout: 0, action: { label: '撤销', run: () => { ran += 1; } } });
tick(14999); out.actionBefore = alive(action);
tick(181); out.actionAfter = alive(action);
const long = toast('已复制', 'ok', { timeout: 120000 });
tick(15180); out.longAfter = alive(long);
const pending = toast('正在粘贴', 'info', { timeout: 0, pending: true });
tick(60000); out.pending = alive(pending); pending(); tick(180);
const error = toast('无法保存', 'error', { action: { label: '重试', run: () => { ran += 1; } } });
tick(60000); out.errorBefore = alive(error);
error.el.querySelector('button').click(); tick(180);
out.errorAfter = root.contains(error.el); out.ran = ran;
const paused = toast('已保存');
tick(1000); event(paused, 'pointerenter'); tick(10000);
event(paused, 'focusin'); event(paused, 'pointerleave'); tick(5000);
out.focusPauses = alive(paused);
event(paused, 'focusout', paused.el.querySelector('button')); tick(5000);
out.internalFocusPauses = alive(paused);
event(paused, 'focusout'); tick(2199); out.resumeBefore = alive(paused);
tick(181); out.resumeAfter = alive(paused);
mock.timers.reset();
console.log(JSON.stringify(out));
