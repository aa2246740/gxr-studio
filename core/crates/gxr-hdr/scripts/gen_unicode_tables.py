"""Generate `src/unicode_tables.rs` from the reference Python's Unicode database.

Run from the repository root with the project's interpreter (the `uv.lock` Python):

    uv run --frozen python -I core/crates/gxr-hdr/scripts/gen_unicode_tables.py

Every code point is enumerated through the same calls `gxr_studio/hdr/capture.py` relies on:
`str.isspace` (what `str.split()` and `float()` treat as whitespace), `unicodedata.decimal`
(what `float(str)` maps to ASCII digits) and `str.casefold` (full case folding). The data is
the Unicode Character Database, under the Unicode License v3 (see the crate `NOTICE`).
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "src" / "unicode_tables.rs"


def chars():
    for cp in range(sys.maxunicode + 1):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        yield cp, chr(cp)


def array(name: str, values: list[int]) -> str:
    body = ", ".join(f"0x{v:x}" for v in values)
    return f"pub const {name}: [u32; {len(values)}] = [{body}];\n"


def main() -> None:
    space = [cp for cp, c in chars() if c.isspace()]
    zeros = []
    for cp, c in chars():
        d = unicodedata.decimal(c, -1)
        if d == -1:
            continue
        if d == 0:
            zeros.append(cp)
        # Every decimal digit sits in a run of ten that starts at its zero.
        assert unicodedata.decimal(chr(cp - d), -1) == 0, hex(cp)
    for z in zeros:
        assert [unicodedata.decimal(chr(z + i), -1) for i in range(10)] == list(range(10)), hex(z)
    single_k, single_v, multi_k, multi_v = [], [], [], []
    for cp, c in chars():
        f = c.casefold()
        if f == c:
            continue
        if len(f) == 1:
            single_k.append(cp)
            single_v.append(ord(f))
        else:
            assert len(f) <= 3, hex(cp)
            multi_k.append(cp)
            multi_v.extend([ord(x) for x in f] + [0] * (3 - len(f)))
    text = (
        "//! Generated by `scripts/gen_unicode_tables.py`; do not edit by hand.\n"
        f"//! Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version} "
        "(Unicode Character Database, Unicode License v3; see `NOTICE`).\n\n"
        "/// Code points for which `str.isspace()` is true, ascending.\n"
        + array("PY_SPACE", space)
        + "\n/// Code points whose `unicodedata.decimal` is 0; digits 1-9 follow each one.\n"
        + array("DECIMAL_ZERO", zeros)
        + "\n/// `str.casefold()` of one code point to one code point: keys ascending.\n"
        + array("FOLD1_KEY", single_k)
        + "\n/// The folded code point for each `FOLD1_KEY`.\n"
        + array("FOLD1_VAL", single_v)
        + "\n/// `str.casefold()` of one code point to two or three: keys ascending.\n"
        + array("FOLDN_KEY", multi_k)
        + "\n/// Three code points per `FOLDN_KEY`, 0-padded.\n"
        + array("FOLDN_VAL", multi_v)
    )
    OUT.write_text(text, encoding="utf-8")
    print(f"{OUT}: {len(space)} spaces, {len(zeros)} digit runs, {len(single_k)} + {len(multi_k)} folds")


if __name__ == "__main__":
    main()
